#!/usr/bin/env python3
"""
Build the app's index of OpenElections precinct-results files, one small JSON per state.

OpenElections (https://openelections.net) is a volunteer project that publishes
certified election results as CSV files, one GitHub repository per state
(openelections/openelections-data-XX). The app lists these files from the
bundled index (app/data/openelections/XX.json) and downloads only the file a
candidate picks, straight from GitHub. Rerun this script now and then to pick
up new files.

Usage (from the campaign-in-a-box folder; needs git, standard library only):
  python3 tools/sync_openelections_index.py            # all states
  python3 tools/sync_openelections_index.py ut co      # just these
"""
import datetime as dt
import json
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "app", "data", "openelections")
STATES = ("al ak az ar ca co ct de dc fl ga hi id il in ia ks ky la me md ma mi mn ms mo mt ne nv nh nj "
          "nm ny nc nd oh ok or pa ri sc sd tn tx ut vt va wa wv wi wy").split()
NAME = re.compile(r"(?P<date>\d{8})__(?P<st>[a-z]{2})__(?P<rest>.+?)__(?P<unit>precinct|ward|town)\.csv$", re.I)
KINDS = ("general", "primary", "special", "runoff", "municipal", "special__general", "special__primary")


def git(*args, cwd=None):
    return subprocess.run(["git", "-c", "gc.auto=0", *args], cwd=cwd, check=True, capture_output=True, text=True).stdout


def index_state(st, work):
    repo = f"https://github.com/openelections/openelections-data-{st}.git"
    dest = os.path.join(work, st)
    git("clone", "-q", "--depth", "1", "--filter=blob:none", "--no-checkout", repo, dest)
    branch = git("rev-parse", "--abbrev-ref", "HEAD", cwd=dest).strip()
    files = []
    for path in git("ls-tree", "-r", "--name-only", "HEAD", cwd=dest).splitlines():
        m = NAME.search(os.path.basename(path))
        if not m:
            continue
        rest = m.group("rest").lower()
        kind, county = rest, ""
        for k in sorted(KINDS, key=len, reverse=True):
            if rest == k:
                kind, county = k, ""
                break
            if rest.startswith(k + "__"):
                kind, county = k, rest[len(k) + 2:]
                break
        else:
            parts = rest.split("__")
            kind, county = parts[0], "__".join(parts[1:])
        files.append({"path": path, "date": m.group("date"), "kind": kind.replace("__", " "),
                      "county": county.replace("_", " ").strip(), "unit": m.group("unit").lower()})
    files.sort(key=lambda f: (f["date"], f["county"]), reverse=True)
    return {"state": st.upper(), "repo": f"openelections/openelections-data-{st}", "branch": branch,
            "indexed": dt.date.today().isoformat(), "files": files}


def main():
    wanted = [s.lower() for s in sys.argv[1:]] or STATES
    os.makedirs(OUT, exist_ok=True)
    summary = {}
    with tempfile.TemporaryDirectory() as work:
        for st in wanted:
            try:
                data = index_state(st, work)
            except subprocess.CalledProcessError as e:
                print(f"{st}: skipped ({e.stderr.strip()[:80]})")
                continue
            with open(os.path.join(OUT, f"{st}.json"), "w", encoding="utf-8") as f:
                json.dump(data, f, separators=(",", ":"))
            summary[st.upper()] = len(data["files"])
            print(f"{st}: {len(data['files'])}", end="  ", flush=True)
    idx_path = os.path.join(OUT, "index.json")
    old = {}
    if os.path.exists(idx_path):
        with open(idx_path, encoding="utf-8") as f:
            old = json.load(f).get("counts", {})
    old.update(summary)
    with open(idx_path, "w", encoding="utf-8") as f:
        json.dump({"indexed": dt.date.today().isoformat(), "counts": old}, f, separators=(",", ":"))
    # File counts the app shows before anything is downloaded.
    with open(os.path.join(HERE, "..", "app", "js", "oe-counts.js"), "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/sync_openelections_index.py. */\n")
        f.write(f"window.CIB_OE_COUNTS = {json.dumps(old, separators=(',', ':'))};\n")
        f.write(f"window.CIB_OE_INDEXED = {json.dumps(dt.date.today().isoformat())};\n")


if __name__ == "__main__":
    main()
