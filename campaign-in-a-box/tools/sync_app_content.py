#!/usr/bin/env python3
"""
Copy the kit's shared content into the no-code app.

The web app (app/) runs with no build step, so it can't read the kit's JSON,
CSV and Markdown files at runtime from GitHub Pages without extra requests.
This script bundles them into one file, app/js/content.js. Run it after you
edit any of these:

  creative/brand/brand.json             palettes, type pairings, contrast rules
  creative/campaign.example.json        the fictional Rivertown example campaign
  examples/rivertown-precincts.csv      the example's past precinct results
  creative/email/messages/*.md          the email sequence templates
  app/fonts/*.woff2                     the brand fonts (bundled as app/js/fonts-data.js)

Usage (from the campaign-in-a-box folder):
  python3 tools/sync_app_content.py
Standard library only.
"""
import base64
import csv
import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
KIT = os.path.abspath(os.path.join(HERE, ".."))
OUT = os.path.join(KIT, "app", "js", "content.js")


def read(path):
    with open(os.path.join(KIT, path), encoding="utf-8") as f:
        return f.read()


def main():
    brand = json.loads(read("creative/brand/brand.json"))
    example = json.loads(read("creative/campaign.example.json"))
    with open(os.path.join(KIT, "examples/rivertown-precincts.csv"), newline="", encoding="utf-8-sig") as f:
        precincts = list(csv.DictReader(f))
    emails = {}
    for path in sorted(glob.glob(os.path.join(KIT, "creative/email/messages/*.md"))):
        name = os.path.splitext(os.path.basename(path))[0]
        with open(path, encoding="utf-8") as f:
            emails[name] = f.read()
    data = {
        "_generated_by": "tools/sync_app_content.py — do not edit by hand; edit the source files and rerun.",
        "brand": brand,
        "example": example,
        "examplePrecincts": precincts,
        "emails": emails,
    }
    body = json.dumps(data, ensure_ascii=False, indent=1)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/sync_app_content.py. Do not edit by hand. */\n")
        f.write("window.CIB_CONTENT = " + body + ";\n")
    print(f"Wrote {os.path.relpath(OUT, KIT)} ({len(body):,} bytes)")

    # Brand fonts as base64, so the app can measure and embed them with no network requests
    # (this also lets index.html work when opened straight from a downloaded folder).
    fonts_dir = os.path.join(KIT, "app", "fonts")
    fonts = {}
    for path in sorted(glob.glob(os.path.join(fonts_dir, "*.woff2"))):
        with open(path, "rb") as f:
            fonts[os.path.basename(path)] = base64.b64encode(f.read()).decode("ascii")
    fout = os.path.join(KIT, "app", "js", "fonts-data.js")
    with open(fout, "w", encoding="ascii") as f:
        f.write("/* Generated by tools/sync_app_content.py from app/fonts/*.woff2 (SIL Open Font License). */\n")
        f.write("window.CIB_FONTS = " + json.dumps(fonts, indent=0) + ";\n")
    print(f"Wrote {os.path.relpath(fout, KIT)} ({len(fonts)} fonts)")


if __name__ == "__main__":
    main()
